#!/usr/bin/env python3
"""Write changelog_data.py (from CHANGELOG.md) and guide_data.py (the how-to-use part of README.md, between
the <!-- guide:start --> and <!-- guide:end --> markers) so the app can show them in Settings.

The release workflow runs this before every build, so a built app always carries the changelog
of its own version. Run it by hand if you want the same when running from source."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

with open(os.path.join(ROOT, "CHANGELOG.md"), encoding="utf-8") as f:
    text = f.read()
with open(os.path.join(ROOT, "changelog_data.py"), "w", encoding="utf-8", newline="\n") as f:
    f.write('"""Generated by scripts/embed_changelog.py from CHANGELOG.md - do not edit."""\n\n')
    f.write("CHANGELOG = " + repr(text) + "\n")
print("changelog_data.py written")

with open(os.path.join(ROOT, "README.md"), encoding="utf-8") as f:
    readme = f.read()
start, end = "<!-- guide:start -->", "<!-- guide:end -->"
if start not in readme or end not in readme:
    raise SystemExit("README.md has no guide markers")
guide = readme.split(start, 1)[1].split(end, 1)[0].strip() + "\n"
with open(os.path.join(ROOT, "guide_data.py"), "w", encoding="utf-8", newline="\n") as f:
    f.write('"""Generated by scripts/embed_changelog.py from README.md - do not edit."""\n\n')
    f.write("GUIDE = " + repr(guide) + "\n")
print("guide_data.py written")
